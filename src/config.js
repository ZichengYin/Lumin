/** 每拍多少毫秒 */
export function msPerBeat(bpm) {
  return 60000 / bpm;
}

/** 角度差（度）→ 时间差（毫秒），需要给定那一段转一圈要多少毫秒 */
export function angleDegToMs(deg, msPerTurn) {
  return (deg / 360) * msPerTurn;
}
